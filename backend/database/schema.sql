CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(160) NOT NULL UNIQUE,
  phone VARCHAR(24) NOT NULL,
  nic_number VARCHAR(30) NOT NULL UNIQUE,
  address VARCHAR(500) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  subject VARCHAR(160) NOT NULL,
  message VARCHAR(2000) NOT NULL,
  status VARCHAR(30) DEFAULT 'Received' NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_inquiry_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS claims (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  policy_number VARCHAR(50) NOT NULL,
  claim_type VARCHAR(40) NOT NULL,
  incident_date DATE NOT NULL,
  incident_location VARCHAR(240) NOT NULL,
  estimated_amount DECIMAL(14,2) NOT NULL CHECK (estimated_amount >= 0),
  description VARCHAR(2500) NOT NULL,
  status VARCHAR(30) DEFAULT 'Submitted' NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_claim_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  policy_number VARCHAR(50) NOT NULL,
  amount DECIMAL(14,2) NOT NULL CHECK (amount > 0),
  payment_method VARCHAR(30) NOT NULL,
  reference_number VARCHAR(60) NOT NULL UNIQUE,
  status VARCHAR(30) DEFAULT 'Paid' NOT NULL,
  paid_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_payment_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  feedback_type VARCHAR(20) NOT NULL,
  rating INTEGER CHECK (rating BETWEEN 1 AND 5),
  title VARCHAR(160) NOT NULL,
  message VARCHAR(2000) NOT NULL,
  status VARCHAR(30) DEFAULT 'Published' NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_feedback_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_claims_user ON claims(user_id);
CREATE INDEX IF NOT EXISTS idx_payments_user ON payments(user_id);
CREATE INDEX IF NOT EXISTS idx_feedback_created ON feedback(created_at);

CREATE TABLE IF NOT EXISTS vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  registration_number VARCHAR(30) NOT NULL,
  vehicle_type VARCHAR(40) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_vehicle_user_registration UNIQUE (user_id, registration_number),
  CONSTRAINT fk_vehicle_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS agents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(160) NOT NULL UNIQUE,
  phone VARCHAR(24),
  password_hash VARCHAR(100) NOT NULL,
  active BOOLEAN DEFAULT TRUE NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS accident_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_number VARCHAR(40) NOT NULL UNIQUE,
  user_id BIGINT NOT NULL,
  vehicle_id BIGINT NOT NULL,
  contact_number VARCHAR(24) NOT NULL,
  incident_type VARCHAR(30) NOT NULL,
  incident_at TIMESTAMP NOT NULL,
  accident_location VARCHAR(240) NOT NULL,
  description VARCHAR(2500) NOT NULL,
  status VARCHAR(30) DEFAULT 'Pending' NOT NULL,
  assigned_agent_id BIGINT,
  submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_accident_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_accident_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id),
  CONSTRAINT fk_accident_agent FOREIGN KEY (assigned_agent_id) REFERENCES agents(id),
  CONSTRAINT chk_accident_status CHECK (status IN ('Pending','Under Review','Agent Contacted','Processing','Approved','Rejected','Closed'))
);

CREATE TABLE IF NOT EXISTS accident_photos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id BIGINT NOT NULL,
  stored_name VARCHAR(255) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  file_size BIGINT NOT NULL,
  uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_photo_notification FOREIGN KEY (notification_id) REFERENCES accident_notifications(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS claim_status_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notification_id BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL,
  note VARCHAR(500),
  changed_by_agent_id BIGINT,
  changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_history_notification FOREIGN KEY (notification_id) REFERENCES accident_notifications(id) ON DELETE CASCADE,
  CONSTRAINT fk_history_agent FOREIGN KEY (changed_by_agent_id) REFERENCES agents(id)
);

CREATE INDEX IF NOT EXISTS idx_vehicles_user ON vehicles(user_id);
CREATE INDEX IF NOT EXISTS idx_accidents_user ON accident_notifications(user_id);
CREATE INDEX IF NOT EXISTS idx_accidents_status ON accident_notifications(status);
CREATE INDEX IF NOT EXISTS idx_photos_notification ON accident_photos(notification_id);
CREATE INDEX IF NOT EXISTS idx_history_notification ON claim_status_history(notification_id);
